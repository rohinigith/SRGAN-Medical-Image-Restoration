class MedicalImageDataset(Dataset):
    def __init__(self, root_dir, lr_size=(64,64), hr_size=(256,256)):
        self.root_dir = root_dir

        valid_ext = ('.png', '.jpg', '.jpeg', '.bmp', '.tiff')
        self.image_filenames = [f for f in os.listdir(root_dir) if f.lower().endswith(valid_ext)]
        print(f"Found {len(self.image_filenames)} images")

        self.lr_transform = transforms.Compose([
            transforms.Resize(lr_size),
            transforms.ToTensor(),
            transforms.Normalize([0.5], [0.5])
        ])

        self.hr_transform = transforms.Compose([
            transforms.Resize(hr_size),
            transforms.ToTensor(),
            transforms.Normalize([0.5], [0.5])
        ])

    def __len__(self):
        return len(self.image_filenames)

    def __getitem__(self, idx):
        img_path = os.path.join(self.root_dir, self.image_filenames[idx])
        img = Image.open(img_path).convert('L')

        hr_img = self.hr_transform(img)
        lr_img = self.lr_transform(img)

        return lr_img, hr_img

