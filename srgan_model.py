class ResidualBlock(nn.Module):
    def __init__(self, channels):
        super().__init__()
        self.block = nn.Sequential(
            nn.Conv2d(channels, channels, kernel_size=3, padding=1),
            nn.BatchNorm2d(channels),
            nn.PReLU(),
            nn.Conv2d(channels, channels, kernel_size=3, padding=1),
            nn.BatchNorm2d(channels)
        )
    def forward(self, x):
        return x + self.block(x)

class Generator(nn.Module):
    def __init__(self, num_residual_blocks=16, upsample_factor=4):
        super().__init__()

        assert upsample_factor in [2, 4, 8], "Unsupported upscale factor"

        self.conv1 = nn.Sequential(
            nn.Conv2d(1, 64, kernel_size=9, padding=4),
            nn.PReLU()
        )

        self.residual_blocks = nn.Sequential(
            *[ResidualBlock(64) for _ in range(num_residual_blocks)]
        )

        self.conv2 = nn.Sequential(
            nn.Conv2d(64, 64, kernel_size=3, padding=1),
            nn.BatchNorm2d(64)
        )

        upsample_layers = []
        for _ in range(int(torch.log2(torch.tensor(upsample_factor)))):
            upsample_layers += [
                nn.Conv2d(64, 256, kernel_size=3, padding=1),
                nn.PixelShuffle(2),
                nn.PReLU()
            ]

        self.upsampling = nn.Sequential(*upsample_layers)

        self.conv3 = nn.Conv2d(64, 1, kernel_size=9, padding=4)
        self.tanh = nn.Tanh()

    def forward(self, x):
        out1 = self.conv1(x)
        out = self.residual_blocks(out1)
        out2 = self.conv2(out)
        out = out1 + out2
        out = self.upsampling(out)
        out = self.conv3(out)
        out = self.tanh(out)
        return out

class Discriminator(nn.Module):
    def __init__(self):
        super().__init__()
        net = []
        def d_block(in_ch, out_ch, stride=1):
            layers = [nn.Conv2d(in_ch, out_ch, kernel_size=3, stride=stride, padding=1)]
            layers += [nn.BatchNorm2d(out_ch), nn.LeakyReLU(0.2, inplace=True)]
            return layers

        net += [nn.Conv2d(1, 64, kernel_size=3, stride=1, padding=1), nn.LeakyReLU(0.2, inplace=True)]
        net += d_block(64, 64, stride=2)
        net += d_block(64, 128, stride=1)
        net += d_block(128, 128, stride=2)
        net += d_block(128, 256, stride=1)
        net += d_block(256, 256, stride=2)
        net += d_block(256, 512, stride=1)
        net += d_block(512, 512, stride=2)

        net += [nn.AdaptiveAvgPool2d(1), nn.Flatten()]
        net += [nn.Linear(512, 1024), nn.LeakyReLU(0.2, inplace=True), nn.Linear(1024, 1)]

        self.net = nn.Sequential(*net)

    def forward(self, x):
        return self.net(x)

class VGGFeatureExtractor(nn.Module):
    def __init__(self, device):
        super().__init__()
        vgg = models.vgg19(pretrained=True).features[:35].to(device).eval()
        for p in vgg.parameters():
            p.requires_grad = False
        self.vgg = vgg

    def forward(self, x):
        if x.shape[1] == 1:
            x = x.repeat(1, 3, 1, 1)
        return self.vgg(x)

